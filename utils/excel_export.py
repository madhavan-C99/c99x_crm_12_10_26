import openpyxl
from openpyxl.styles import Font, Alignment, PatternFill, Border, Side
from openpyxl.utils import get_column_letter
from datetime import datetime


def format_generated_by(user):
    """
    Formats the user and organization name in 'Username | C99x CRM' format.
    Example: 'Gunalraj k | C99x CRM'
    """
    if not user or not getattr(user, "is_authenticated", False):
        return "Admin | C99x CRM"

    # User display name
    full_name = f"{getattr(user, 'first_name', '') or ''} {getattr(user, 'last_name', '') or ''}".strip()
    user_name = full_name or getattr(user, 'username', 'User')

    return f"{user_name} | C99x CRM"


def apply_excel_report_header(
    ws,
    report_name="Report",
    description="All in one report",
    user=None,
    generated_at=None
):
    """
    Applies standard top metadata headers (Rows 1-4) matching the required spec:
      Row 1: Report Name    | <report_name>
      Row 2: Description    | <description>
      Row 3: Generated By   | <username | organization>
      Row 4: Generated At   | <Mon Oct 12 2026>
      Row 5: [blank]
      Row 6: [blank]
    Returns 7 (the row number where table headers should start).
    """
    meta_label_font = Font(name="Calibri", size=11, bold=True, color="000000")
    meta_val_font = Font(name="Calibri", size=11, bold=False, color="1F2937")

    if not generated_at:
        generated_at = datetime.now().strftime("%a %b %d %Y")
    elif isinstance(generated_at, datetime):
        generated_at = generated_at.strftime("%a %b %d %Y")

    generated_by = format_generated_by(user) if user else "Admin | C99x CRM"

    meta_info = [
        ("Report Name", report_name),
        ("Description", description or f"All in one {report_name.lower()}"),
        ("Generated By", generated_by),
        ("Generated At", str(generated_at))
    ]

    for row_idx, (label, val) in enumerate(meta_info, start=1):
        cell_lbl = ws.cell(row=row_idx, column=1, value=label)
        cell_lbl.font = meta_label_font
        cell_lbl.alignment = Alignment(horizontal="left", vertical="center")

        cell_val = ws.cell(row=row_idx, column=2, value=val)
        cell_val.font = meta_val_font
        cell_val.alignment = Alignment(horizontal="left", vertical="center")
        ws.row_dimensions[row_idx].height = 20

    # Spacing rows (Rows 5 & 6)
    ws.row_dimensions[5].height = 15
    ws.row_dimensions[6].height = 15

    return 7


def auto_fit_columns(ws, start_row=7, min_width=14, col_a_min=18, col_b_min=28, max_width=60):
    """
    Automatically adjusts column widths so content isn't truncated or shown as '###'.
    Ensures Column A and Column B have sufficient width for the metadata headers.
    """
    for col_cells in ws.columns:
        if not col_cells:
            continue
        col_letter = get_column_letter(col_cells[0].column)
        max_len = 0

        # Measure from start_row (table header and data rows)
        check_cells = col_cells[start_row - 1:] if len(col_cells) >= start_row else col_cells
        for cell in check_cells:
            val_str = str(cell.value or "")
            if val_str:
                max_len = max(max_len, len(val_str))

        calculated_width = min(max(max_len + 4, min_width), max_width)

        # Ensure Column A & B are wide enough for metadata
        if col_letter == 'A':
            calculated_width = max(calculated_width, col_a_min)
        elif col_letter == 'B':
            calculated_width = max(calculated_width, col_b_min)

        ws.column_dimensions[col_letter].width = calculated_width


def extract_row_value(row, col):
    """
    Intelligently extracts value from row dict:
    1. Exact match: row.get('date')
    2. Case & separator insensitive: 'userName' <-> 'user_name', 'totalCalls' <-> 'total_calls'
    3. Semantic Synonyms: 'connectedCalls' <-> 'total_calls_connected'
    """
    if not isinstance(row, dict):
        return ""

    # 1. Direct match
    if col in row and row[col] is not None:
        return row[col]

    # 2. Normalized match (strips underscores, spaces and lowers case)
    clean_col = str(col).strip().lower().replace(" ", "").replace("_", "")
    for k, v in row.items():
        clean_k = str(k).strip().lower().replace(" ", "").replace("_", "")
        if clean_k == clean_col and v is not None:
            return v

    # 3. Known field synonyms across report types
    synonyms = {
        'user_name': ['username', 'telecaller_name', 'telecallername', 'name', 'agent_name'],
        'total_calls': ['totalcalls', 'calls_made', 'callsmade'],
        'total_calls_connected': ['connectedcalls', 'totalcallsconnected', 'connected_calls', 'connected'],
        'total_calls_unconnected': ['unconnectedcalls', 'totalcallsunconnected', 'unconnected_calls', 'unconnected'],
        'avg_calling_time': ['avgcallingtime', 'avg_calling_duration', 'averagecallingtime'],
    }

    target_syns = synonyms.get(col, [])
    for syn in target_syns:
        for k, v in row.items():
            clean_k = str(k).strip().lower().replace(" ", "").replace("_", "")
            if clean_k == syn and v is not None:
                return v

    return ""
