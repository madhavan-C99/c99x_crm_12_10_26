import os
from datetime import datetime
from reportlab.lib.pagesizes import A4
from reportlab.lib import colors
from reportlab.lib.units import mm
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import SimpleDocTemplate, Table, TableStyle, Paragraph, Spacer

PRIMARY_GREEN = colors.HexColor('#84C225')
BORDER_COLOR  = colors.HexColor('#E2E8F0')
TEXT_DARK     = colors.HexColor('#1E293B')
TEXT_MUTED    = colors.HexColor('#64748B')
BOX_BG        = colors.HexColor('#FAFAFA')


def generate_daily_report_pdf(file_path, data, user=None):
    """
    Generates Daily Telecaller Report matching Page 1 layout:
    1. Rounded Green Banner (Organization Name / Daily Telecaller Report)
    2. Employee & Role, Date & Generated Timestamp
    3. Today's Activity Table (Activity | Count)
    4. Manual Entry (Tomorrow Conversation, Lead For Tomorrow)
    5. Manager Notes Box
    6. Footer 'Generated by CRM System'
    """
    doc = SimpleDocTemplate(
        file_path,
        pagesize=A4,
        leftMargin=14 * mm,
        rightMargin=14 * mm,
        topMargin=12 * mm,
        bottomMargin=14 * mm
    )
    usable_w = A4[0] - 28 * mm

    title_banner_style = ParagraphStyle('BannerTitle', fontName='Helvetica-Bold', fontSize=13, textColor=colors.white, leading=16)
    sub_banner_style   = ParagraphStyle('BannerSub', fontName='Helvetica', fontSize=10, textColor=colors.white, leading=13)

    meta_lbl_style = ParagraphStyle('MetaLbl', fontName='Helvetica-Bold', fontSize=9, textColor=TEXT_DARK, leading=13)
    sec_hdr_style  = ParagraphStyle('SecHdr', fontName='Helvetica-Bold', fontSize=10, textColor=TEXT_DARK, leading=14)
    th_style       = ParagraphStyle('TH', fontName='Helvetica-Bold', fontSize=9, textColor=colors.white, alignment=1, leading=11)
    td_lbl_style   = ParagraphStyle('TDLbl', fontName='Helvetica', fontSize=8.5, textColor=TEXT_DARK, leading=11)
    td_cnt_style   = ParagraphStyle('TDCnt', fontName='Helvetica', fontSize=8.5, textColor=TEXT_DARK, alignment=1, leading=11)

    manual_lbl_style = ParagraphStyle('MLbl', fontName='Helvetica-Bold', fontSize=9, textColor=TEXT_DARK, leading=13)
    note_txt_style   = ParagraphStyle('NoteTxt', fontName='Helvetica', fontSize=8.5, textColor=TEXT_MUTED, leading=12)

    elements = []

    # 1. Top Green Banner
    org_obj = getattr(user, 'organization', None)
    org_display = (
        getattr(org_obj, 'organization_name', None) or
        getattr(org_obj, 'display_name', None) or
        "CRM System"
    )
    banner_content = [
        [Paragraph(f"<b>{org_display}</b>", title_banner_style)],
        [Paragraph("Daily Telecaller Report", sub_banner_style)]
    ]
    banner_tbl = Table(banner_content, colWidths=[usable_w])
    banner_tbl.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), PRIMARY_GREEN),
        ('TOPPADDING', (0, 0), (-1, -1), 4 * mm),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4 * mm),
        ('LEFTPADDING', (0, 0), (-1, -1), 5 * mm),
    ]))
    elements.append(banner_tbl)
    elements.append(Spacer(1, 5 * mm))

    # 2. Metadata (Employee, Role, Date, Generated)
    emp_name = data.get('user') or (getattr(user, 'username', 'Bharath') if user else 'Bharath')
    role_name = getattr(user, 'role', 'Executive')
    report_date = str(data.get('report_date') or datetime.now().strftime('%Y-%m-%d'))
    now_str = datetime.now().strftime('%d/%m/%Y, %H:%M:%S')

    meta_data = [
        [Paragraph(f"<b>Employee :</b> {emp_name}", meta_lbl_style), Paragraph(f"<b>Role :</b> {role_name}", meta_lbl_style)],
        [Paragraph(f"<b>Date :</b> {report_date}", meta_lbl_style), Paragraph(f"<b>Generated :</b> {now_str}", meta_lbl_style)]
    ]
    meta_tbl = Table(meta_data, colWidths=[usable_w * 0.5, usable_w * 0.5])
    meta_tbl.setStyle(TableStyle([
        ('TOPPADDING', (0, 0), (-1, -1), 1.5 * mm),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 1.5 * mm),
        ('LEFTPADDING', (0, 0), (-1, -1), 0),
    ]))
    elements.append(meta_tbl)
    elements.append(Spacer(1, 3 * mm))

    # 3. Today's Activity Table
    elements.append(Paragraph("<b>Today's Activity</b>", sec_hdr_style))
    elements.append(Spacer(1, 2 * mm))

    activity_rows = [
        ('Total Leads', data.get('total_leads', 0)),
        ('New Leads', data.get('new_leads', 0)),
        ('Call Spoked', data.get('call_spoked', 0)),
        ('Not Respond', data.get('not_respond', 0)),
        ('Follow Up', data.get('follow_up', 0)),
        ('Pending Follow Up', data.get('pending_follow_up', 0)),
        ('Partial Payment', data.get('partial_payment', 0)),
        ('Full Payment', data.get('full_payment', 0)),
    ]

    act_tbl_data = [[Paragraph("Activity", th_style), Paragraph("Count", th_style)]]
    for lbl, count in activity_rows:
        act_tbl_data.append([Paragraph(lbl, td_lbl_style), Paragraph(str(count), td_cnt_style)])

    act_tbl = Table(act_tbl_data, colWidths=[usable_w * 0.75, usable_w * 0.25])
    act_tbl.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), PRIMARY_GREEN),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('TOPPADDING', (0, 0), (-1, -1), 2 * mm),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 2 * mm),
        ('BOX', (0, 0), (-1, -1), 0.5, BORDER_COLOR),
        ('INNERGRID', (0, 0), (-1, -1), 0.5, BORDER_COLOR),
    ]))
    elements.append(act_tbl)
    elements.append(Spacer(1, 4 * mm))

    # 4. Manual Entry Section
    elements.append(Paragraph("<b>Manual Entry</b>", sec_hdr_style))
    elements.append(Spacer(1, 2 * mm))

    tmr_conv = str(data.get('tomorrow_conversation') or data.get('total_expected_conversion') or '0')
    lead_tmr = str(data.get('lead_for_tomorrow') or data.get('actual_expected_conversion') or '0')
    notes = data.get('own_message') or data.get('notes_for_manager') or 'No notes provided'

    manual_data = [
        [Paragraph(f"<b>Tomorrow Conversation :</b> {tmr_conv}", manual_lbl_style)],
        [Paragraph(f"<b>Lead For Tomorrow :</b> {lead_tmr}", manual_lbl_style)],
        [Spacer(1, 1 * mm)],
        [Paragraph("<b>Manager Notes</b>", manual_lbl_style)],
        [Paragraph(notes, note_txt_style)],
    ]
    manual_tbl = Table(manual_data, colWidths=[usable_w])
    manual_tbl.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), BOX_BG),
        ('BOX', (0, 0), (-1, -1), 0.5, BORDER_COLOR),
        ('TOPPADDING', (0, 0), (-1, -1), 2 * mm),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 2 * mm),
        ('LEFTPADDING', (0, 0), (-1, -1), 4 * mm),
    ]))
    elements.append(manual_tbl)
    elements.append(Spacer(1, 8 * mm))

    # 5. Footer Text
    footer_style = ParagraphStyle('Footer', fontName='Helvetica', fontSize=8, textColor=TEXT_MUTED, alignment=1)
    elements.append(Paragraph("Generated by CRM System", footer_style))

    doc.build(elements)
